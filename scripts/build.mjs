import { readFile, writeFile, mkdir, cp, rm, readdir, stat } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';

const project = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = resolve(project, 'dist');
const moduleNames = ['scene', 'media', 'navigation', 'content'];
const bundled = [];
for (const name of moduleNames) {
  const source = await readFile(resolve(project, `src/${name}.js`), 'utf8');
  const exports = [...source.matchAll(/^export\s+(?:(?:async\s+)?function|const|class)\s+([\w$]+)/gm)].map((match) => match[1]);
  if (!exports.length || /^import\s/m.test(source)) throw new Error(`Unsupported module form: ${name}`);
  bundled.push(`const ${name}Module = (() => {\n${source.replace(/^export\s+/gm, '')}\nreturn { ${exports.join(', ')} };\n})();`);
}
let main = await readFile(resolve(project, 'src/main.js'), 'utf8');
main = main.replace(/^import\s+\{([^}]+)\}\s+from\s+['"]\.\/(\w+)\.js['"];?\s*$/gm, (_, names, name) => {
  if (!moduleNames.includes(name)) throw new Error(`Unknown module ${name}`);
  return `const {${names}} = ${name}Module;`;
});
if (/^import\s/m.test(main)) throw new Error('Unbundled main import.');
const javascript = `/* little clover garden — generated by scripts/build.mjs */\n(() => {\n'use strict';\n${bundled.join('\n')}\n${main}\n})();\n`;
const fingerprint=(content)=>createHash('sha256').update(content).digest('hex').slice(0,8);
const scriptName=`app.${fingerprint(javascript)}.js`;
const stylesheet=await readFile(resolve(project,'src/styles.css'),'utf8');
const styleName=`styles.${fingerprint(stylesheet)}.css`;
await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
await cp(resolve(project, 'assets'), resolve(output, 'assets'), { recursive: true });
await writeFile(resolve(output,styleName),stylesheet);
await writeFile(resolve(output,scriptName),javascript);
let html = await readFile(resolve(project, 'index.html'), 'utf8');
html = html.replace('./src/styles.css', `./${styleName}`).replace('<script type="module" src="./src/main.js"></script>', `<script defer src="./${scriptName}"></script>`);
await writeFile(resolve(output, 'index.html'), html);
await writeFile(resolve(output, '.nojekyll'), '');
const check = spawnSync(process.execPath, ['--check', resolve(output,scriptName)], { encoding: 'utf8' });
if (check.status !== 0) throw new Error(check.stderr || 'Bundled JavaScript syntax check failed.');
for (const match of html.matchAll(/(?:src|href)="(\.\/[^"?#]+)"/g)) {
  await stat(resolve(output, match[1]));
}
let total = 0;
async function count(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) await count(path); else total += (await stat(path)).size;
  }
}
await count(output);
console.log(`Built dist/ (${(total / 1024 / 1024).toFixed(2)} MiB). Relative asset paths support GitHub project Pages and local file preview.`);
