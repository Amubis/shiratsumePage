import { readFile, writeFile, mkdir, cp, rm, readdir, stat } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { embedOwnerProfileData } from './owner-profile-data.mjs';
import { embedGardenData } from './garden-data.mjs';

const project = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = resolve(project, 'dist');
const moduleNames = ['garden-content', 'garden-runtime', 'content-availability', 'comments', 'photo-likes', 'scene', 'water-footer', 'media', 'navigation', 'content', 'outfit-rail-feedback', 'outfits', 'album-player-motion', 'album-page-motion', 'album-layout', 'album-pagination', 'album-neighbors', 'album', 'intro-entrance', 'album-transition', 'album-scroll', 'motion', 'sidebar', 'stable-clip', 'contrast', 'transition-preview', 'owner-profile', 'personal-page', 'video-reveal', 'hero-interactions', 'personal-entrance', 'topbar-dock', 'model-switch-motion', 'language-transition', 'owner-tools'];
const bundled = [];
const emitted=new Set();
function rewriteImports(source,available){
  const rewritten=source.replace(/^import\s+\{([^}]+)\}\s+from\s+['"]\.\/([\w-]+)\.js['"];?\s*$/gm,(_,names,name)=>{
    if(!available.has(name))throw new Error(`Unknown or unordered module ${name}`);
    return `const {${names.replace(/\b(\w+)\s+as\s+(\w+)\b/g,'$1: $2')}}=${name.replace(/-/g,'_')}Module;`;
  });
  if(/^import\s/m.test(rewritten))throw new Error('Unsupported module import.');
  return rewritten;
}
for (const name of moduleNames) {
  const source = await readFile(resolve(project, `src/${name}.js`), 'utf8');
  const exports = [...source.matchAll(/^export\s+(?:(?:async\s+)?function|const|class)\s+([\w$]+)/gm)].map((match) => match[1]);
  if (!exports.length) throw new Error(`Unsupported module form: ${name}`);
  const body=rewriteImports(source.replace(/^export\s+/gm,''),emitted);
  bundled.push(`const ${name.replace(/-/g,'_')}Module = (() => {\n${body}\nreturn { ${exports.join(', ')} };\n})();`);
  emitted.add(name);
}
let main = await readFile(resolve(project, 'src/main.js'), 'utf8');
main=rewriteImports(main,emitted);
const javascript = `/* little clover garden — generated by scripts/build.mjs */\n(() => {\n'use strict';\n${bundled.join('\n')}\n${main}\n})();\n`;
const fingerprint=(content)=>createHash('sha256').update(content).digest('hex').slice(0,8);
const scriptName=`app.${fingerprint(javascript)}.js`;
const stylesheet=(await Promise.all(['styles','refinements','owner-profile','video-reveal','outfits','model-intro','water-theme','hero-interactions','intro-entrance','album','album-transition','album-page','album-player-motion','personal-page','topbar-dock','comments','photo-likes','water-footer','art-direction','outfit-rail-feedback','model-space-transition','language-transition','owner-tools','content-availability','ui-text'].map(name=>readFile(resolve(project,`src/${name}.css`),'utf8')))).join('\n');
const styleName=`styles.${fingerprint(stylesheet)}.css`;
await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
await cp(resolve(project, 'assets'), resolve(output, 'assets'), { recursive: true });
// Only published records cross the build boundary, even if the editable seed
// contains reviewed drafts. API state and private uploads are never copied.
await mkdir(resolve(output,'data'),{recursive:true});
const garden=JSON.parse(await readFile(resolve(project,'data/garden.json'),'utf8'));
const { publicGardenContent }=await import('../src/garden-content.js');
const published=publicGardenContent(garden);
for(const [name,value] of Object.entries({garden:published,owner:published.owner,album:{schemaVersion:1,media:published.media},outfits:{schemaVersion:1,outfits:published.outfits},runtime:JSON.parse(await readFile(resolve(project,'data/runtime.json'),'utf8'))}))await writeFile(resolve(output,`data/${name}.json`),JSON.stringify(value,null,2)+'\n');
await cp(resolve(project,'admin'),resolve(output,'admin'),{recursive:true});
await mkdir(resolve(output,'src'),{recursive:true});
for(const name of ['garden-content','photo-metadata','editor-copy-fields'])await cp(resolve(project,`src/${name}.js`),resolve(output,`src/${name}.js`));
await cp(resolve(project,'src/ui-text.css'),resolve(output,'src/ui-text.css'));
await writeFile(resolve(output,styleName),stylesheet);
await writeFile(resolve(output,scriptName),javascript);
let html = await readFile(resolve(project, 'index.html'), 'utf8');
html = embedGardenData(embedOwnerProfileData(html, published.owner),published);
html = html.replace('./src/styles.css', `./${styleName}`).replace('<script type="module" src="./src/main.js"></script>', `<script defer src="./${scriptName}"></script>`);
for(const name of ['refinements','owner-profile','video-reveal','outfits','model-intro','water-theme','hero-interactions','intro-entrance','album','album-transition','album-page','album-player-motion','personal-page','topbar-dock','comments','photo-likes','water-footer','art-direction','outfit-rail-feedback','model-space-transition','language-transition','owner-tools','content-availability','ui-text'])html=html.replace(`  <link rel="stylesheet" href="./src/${name}.css">\n`,'');
await writeFile(resolve(output, 'index.html'), html);
await writeFile(resolve(output, '.nojekyll'), '');
const check = spawnSync(process.execPath, ['--check', resolve(output,scriptName)], { encoding: 'utf8' });
if (check.status !== 0) throw new Error(check.stderr || 'Bundled JavaScript syntax check failed.');
for (const match of html.matchAll(/(?:src|href)="(\.\/[^"?#]+)"/g)) {
  await stat(resolve(output, match[1]));
}
let total = 0;
async function count(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) await count(path); else total += (await stat(path)).size;
  }
}
await count(output);
console.log(`Built dist/ (${(total / 1024 / 1024).toFixed(2)} MiB). Relative asset paths support GitHub project Pages and local file preview.`);
